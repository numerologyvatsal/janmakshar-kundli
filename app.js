  function refineSaturnTransition(fromDate, toDate, previousKey, moonSign) {
    let low = fromDate.getTime();
    let high = toDate.getTime();
    for (let i = 0; i < 11; i++) {
      const middle = new Date((low + high) / 2);
      if (saturnPhaseAt(middle, moonSign).key === previousKey) low = middle.getTime();
      else high = middle.getTime();
    }
    return new Date(high);
  }

  function calculateSaturnCycles(birthDate, moonSign) {
    const endDate = addDays(birthDate, 85 * 365.2425);
    const cycles = [];
    let segmentStart = birthDate;
    let previousDate = birthDate;
    let previous = saturnPhaseAt(birthDate, moonSign);
    for (let cursor = addDays(birthDate, 30); cursor <= endDate; cursor = addDays(cursor, 30)) {
      const current = saturnPhaseAt(cursor, moonSign);
      if (current.key !== previous.key) {
        const boundary = refineSaturnTransition(previousDate, cursor, previous.key, moonSign);
        if (previous.key !== "normal") cycles.push({ ...previous, start: segmentStart, end: boundary });
        segmentStart = boundary;
        previous = current;
      }
      previousDate = cursor;
    }
    if (previous.key !== "normal") cycles.push({ ...previous, start: segmentStart, end: endDate });
    return cycles;
  }

