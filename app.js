  function calculateSignals(p, ascSign) {
    const signals = [];
    const sameSign = (a, b) => p[a].sign === p[b].sign;
    const kendra = (house) => [1, 4, 7, 10].includes(house);
    const moonToJupiter = ((p.Jupiter.sign - p.Moon.sign + 12) % 12) + 1;

    if (sameSign("Sun", "Mercury")) signals.push({ type: "positive", icon: "☉", title: "બુધાદિત્ય યોગનો સંકેત", text: "સૂર્ય અને બુધ એક રાશિમાં હોવાથી બુદ્ધિ, આયોજન અને અભિવ્યક્તિ સાથે કામ કરવાની ક્ષમતા મજબૂત બની શકે છે." });
    if ([1, 4, 7, 10].includes(moonToJupiter)) signals.push({ type: "positive", icon: "♃", title: "ગજકેસરી યોગનો સંકેત", text: "ચંદ્રથી ગુરુ કેન્દ્રમાં હોવાથી જ્ઞાન, પ્રતિષ્ઠા અને યોગ્ય સમયે સહાય મળવાના શુભ સંકેતો બને છે." });
    if (sameSign("Moon", "Mars")) signals.push({ type: "positive", icon: "◐", title: "ચંદ્ર–મંગળ યોગનો સંકેત", text: "ભાવના અને ક્રિયાશક્તિ સાથે આવે છે; વેપારી સમજ વધે શકે, પણ ઉતાવળથી નિર્ણય ટાળવો." });
    if (sameSign("Jupiter", "Rahu") || sameSign("Jupiter", "Ketu")) signals.push({ type: "caution", icon: "◇", title: "ગુરુ ચાંડાલ સંયોગ", text: "ગુરુ સાથે રાહુ અથવા કેતુનો સંયોગ માન્યતાઓ અને માર્ગદર્શન અંગે ગૂંચવણ આપી શકે; તપાસીને નિર્ણય લેવો શુભ." });
    if ([1, 2, 4, 7, 8, 12].includes(p.Mars.house)) signals.push({ type: "caution", icon: "♂", title: "મંગળ દોષનો પરંપરાગત સંકેત", text: `મંગળ ${p.Mars.house}મા ભાવમાં હોવાથી લગ્નમેળાપમાં અલગથી સંપૂર્ણ ચકાસણી કરવી. એકલા આ યોગ પરથી નિર્ણય ન લેવો.` });

    const classical = ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn"];
    const inRahuArc = classical.every((key) => norm(p[key].longitude - p.Rahu.longitude) <= 180);
    const inKetuArc = classical.every((key) => norm(p[key].longitude - p.Ketu.longitude) <= 180);
    if (inRahuArc || inKetuArc) signals.push({ type: "caution", icon: "☊", title: "કાલસર્પ ગોઠવણીનો સંકેત", text: "સાત મુખ્ય ગ્રહો રાહુ–કેતુની એક બાજુ આવે છે. આ જીવનને વધુ તીવ્ર કે એકાગ્ર બનાવી શકે છે; ફળ માટે સમગ્ર કુંડળી જોવી જરૂરી છે." });

    const panchMahapurush = [
      ["Mars", "રૂચક મહાપુરુષ યોગ"], ["Mercury", "ભદ્ર મહાપુરુષ યોગ"], ["Jupiter", "હંસ મહાપુરુષ યોગ"],
      ["Venus", "માલવ્ય મહાપુરુષ યોગ"], ["Saturn", "શશ મહાપુરુષ યોગ"]
    ];
    panchMahapurush.forEach(([key, title]) => {
      if (kendra(p[key].house) && (EXALT[key] === p[key].sign || (OWN_SIGNS[key] || []).includes(p[key].sign))) {
        signals.push({ type: "positive", icon: "✦", title, text: `${PLANET_NAMES[key]} કેન્દ્ર ભાવમાં ઉચ્ચ અથવા સ્વરાશિમાં હોવાથી તેની ક્ષમતાઓ શક્તિશાળી રીતે વ્યક્ત થઈ શકે છે.` });
      }
    });

    const moonAdjacent = classical.filter((k) => !["Sun", "Moon"].includes(k)).some((k) => {
      const diff = (p[k].sign - p.Moon.sign + 12) % 12; return diff === 1 || diff === 11;
    });
    if (!moonAdjacent) signals.push({ type: "neutral", icon: "☾", title: "ચંદ્રની આસપાસ ગ્રહસહાય ઓછી", text: "ચંદ્રની બાજુની રાશિઓમાં મુખ્ય ગ્રહ ન હોવાથી ક્યારેક અંદરથી એકલા પ્રયાસ કરવાની લાગણી થઈ શકે; કેન્દ્રસ્થિતિ અને દૃષ્ટિથી ફળ બદલાય છે." });

    if (!signals.length) signals.push({ type: "neutral", icon: "◎", title: "મુખ્ય સંયોગ મર્યાદિત", text: "આ સ્વચાલિત નિયમોમાં કોઈ વિશેષ મોટો યોગ કે દોષ મળ્યો નથી. વ્યક્તિગત ફળ માટે ભાવ, દૃષ્ટિ અને દશાનો સંયુક્ત અભ્યાસ જરૂરી છે." });
    return signals;
  }

