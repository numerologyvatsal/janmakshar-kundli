  function dms(longitude) {
    const within = norm(longitude) % 30;
    const d = Math.floor(within);
    const mFloat = (within - d) * 60;
    const m = Math.floor(mFloat);
    const s = Math.round((mFloat - m) * 60);
    return `${d}° ${pad2(m)}′ ${pad2(s)}″`;
  }
