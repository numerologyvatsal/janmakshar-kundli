  function calculatePanchang(input, planets) {
    const elongation = norm(planets.Moon.longitude - planets.Sun.longitude);
    const tithiIndex = Math.floor(elongation / 12);
    const paksha = tithiIndex < 15 ? "શુક્લ પક્ષ" : "કૃષ્ણ પક્ષ";
    const yogaIndex = Math.floor(norm(planets.Sun.longitude + planets.Moon.longitude) / (360 / 27));
    const halfTithi = Math.floor(elongation / 6);
    let karana;
    if (halfTithi === 0) karana = "કિંસ્તુઘ્ન";
    else if (halfTithi >= 57) karana = ["શકુની", "ચતુષ્પદ", "નાગ"][halfTithi - 57] || "નાગ";
    else karana = KARANAS[(halfTithi - 1) % 7];
    const [y, m, d] = input.date.split("-").map(Number);
    const weekday = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
    return { tithi: TITHIS[tithiIndex], tithiNumber: tithiIndex + 1, paksha, yoga: YOGAS[yogaIndex], karana, vara: VARAS[weekday] };
  }

  function calculateDasha(birthDate, nakshatra) {
    const startLordIndex = DASHA_ORDER.indexOf(nakshatra.lord);
    const birthLordYears = DASHA_YEARS[nakshatra.lord];
    const firstStart = addDays(birthDate, -nakshatra.fraction * birthLordYears * 365.2425);
    const periods = [];
    let cursor = firstStart;
    for (let i = 0; i < 9; i++) {
      const lord = DASHA_ORDER[(startLordIndex + i) % 9];
      const end = addDays(cursor, DASHA_YEARS[lord] * 365.2425);
      periods.push({ lord, start: cursor, end, years: DASHA_YEARS[lord] });
      cursor = end;
    }
    const now = new Date();
    const current = periods.find((p) => now >= p.start && now < p.end) || periods[periods.length - 1];
    const subOrderStart = DASHA_ORDER.indexOf(current.lord);
    let subCursor = current.start;
    const subPeriods = [];
    for (let i = 0; i < 9; i++) {
      const lord = DASHA_ORDER[(subOrderStart + i) % 9];
      const durationDays = current.years * DASHA_YEARS[lord] / 120 * 365.2425;
      const end = addDays(subCursor, durationDays);
      subPeriods.push({ lord, start: subCursor, end });
      subCursor = end;
    }
    const currentSub = subPeriods.find((p) => now >= p.start && now < p.end) || subPeriods[0];
    const birthBalanceDays = periods[0].end - birthDate;
    return { periods, current, currentSub, birthBalanceYears: Math.max(0, birthBalanceDays / 86400000 / 365.2425) };
  }

  function dashaAtDate(chart, date) {
    const period = chart.dasha.periods.find((p) => date >= p.start && date < p.end) || chart.dasha.periods[chart.dasha.periods.length - 1];
    const startIndex = DASHA_ORDER.indexOf(period.lord);
    let cursor = period.start;
    const subPeriods = [];
    for (let i = 0; i < 9; i++) {
      const lord = DASHA_ORDER[(startIndex + i) % 9];
      const end = addDays(cursor, period.years * DASHA_YEARS[lord] / 120 * 365.2425);
      subPeriods.push({ lord, start: cursor, end });
      cursor = end;
    }
    const sub = subPeriods.find((p) => date >= p.start && date < p.end) || subPeriods[subPeriods.length - 1];
    return { period, sub };
  }

